"""Extract calibrated Cal Sans ink outlines for portable instrument identities."""
import hashlib
import json
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parents[1]
source = root / "vendor/plotter/assets/fonts/CalSansVF.woff2"
font = TTFont(source)
axes = {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes}
axes.update(wght=400, GEOM=25)
font = instantiateVariableFont(font, axes)
glyphs = font.getGlyphSet()
chars = {}
for code, name in sorted(font.getBestCmap().items()):
    # Printable ASCII, Latin with precomposed accents, plus project punctuation.
    if not (32 <= code <= 126 or 160 <= code <= 383 or 0x2080 <= code <= 0x2089 or code in (0x3A9, 0x394, 0x2013, 0x2014, 0x2212)):
        continue
    glyph = glyphs[name]
    bounds = BoundsPen(glyphs)
    outline = SVGPathPen(glyphs)
    transform = (1, 0, 0, -1, 0, 0)
    glyph.draw(TransformPen(bounds, transform))
    glyph.draw(TransformPen(outline, transform))
    chars[chr(code)] = [glyph.width, bounds.bounds, outline.getCommands()]

data = {
    "font": "Cal Sans Regular GEOM 25 (SIL OFL 1.1)",
    "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "unitsPerEm": font["head"].unitsPerEm,
    "glyphs": chars,
}
output = root / "src/instrument-font.mjs"
output.write_text("// Generated by scripts/build-instrument-font.py.\nexport default " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
